const authorByType = (type) => {
  if (type === "참고자료") return "참고자료";
  if (["제안서","실적표","신청서","신고서","위임장"].includes(type)) return "업체작성";
  if (["평가표","등록부","대장"].includes(type)) return "학교·업체공동";
  return "학교작성";
};

// 계약방법 적용: 준비(전체) / 입찰·평가(수의계약은 핵심서식만) / 계약(수의계약은 F-043만) / 구매·사후(전체) / 참고(해당없음)
const quoteCore = new Set(["F-007", "F-008", "F-009", "F-012"]);
const contractMethodsFor = (id, stage) => {
  if (stage === "참고") return [];
  if (stage === "준비" || stage === "구매" || stage === "사후평가") {
    return ["quote1", "quote2", "twostep", "open"];
  }
  if (stage === "평가") return ["twostep", "open"];
  if (stage === "입찰") {
    const methods = ["twostep", "open"];
    if (quoteCore.has(id)) methods.push("quote1", "quote2");
    return methods;
  }
  if (stage === "계약") {
    if (id === "F-043") return ["quote1", "quote2", "twostep", "open"];
    return ["twostep", "open"];
  }
  return [];
};

const needsField = (id, stage, type) => {
  const base = ["C-01", "C-02", "D-02"];
  if (["기안문","공고문","통보문","가정통신문"].includes(type)) base.push("C-05", "C-06", "C-07", "C-08", "D-01", "D-03", "D-04");
  if (["확인서","서약서","신청서","신고서","위임장","동의서"].includes(type)) base.push("C-07");
  if (id === "F-024" || id === "F-031" || stage === "입찰" && type === "단가표") base.push("items");
  if (["F-021","F-022","F-023"].includes(id)) base.push("companies", "items");
  if (["F-019","F-020","F-027","F-028","F-029","F-030"].includes(id)) base.push("companies");
  if (["F-001","F-002","F-003","F-037","F-040"].includes(id)) base.push("committee");
  if (["F-014","F-015","F-016","F-035","F-036","F-039"].includes(id)) base.push("evaluations");
  if (["F-004","F-005","F-006","F-009","F-041","F-043"].includes(id)) base.push("B-01","B-03","B-04","B-05");
  if (["F-007","F-008","F-011","F-044","F-045","F-046","F-047","F-048"].includes(id)) base.push("B-01","B-06","B-07");
  return Array.from(new Set(base));
};

